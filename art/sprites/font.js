export function textWidth(str, gap = 1) {
  let w = 0;
  for (const ch of str.toUpperCase()) w += (G[ch] || G[' '])[0].length + gap;
  return Math.max(0, w - gap);
}
// returns [[x,y],...] pixel coords of the text with top-left at (x0,y0)
export function textPixels(str, x0, y0, gap = 1) {
  const out = [];
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G[' '];
    for (let y = 0; y < 7; y++) for (let k = 0; k < g[y].length; k++) if (g[y][k] === '1') out.push([x + k, y0 + y]);
    x += g[0].length + gap;
  }
  return out;
}
